# Creates the MTK Browser update signing key pair.
#
# The private key is written OUTSIDE the repository and must never be committed.
# The public key is written into the source tree as a C++ header so the browser
# can verify update manifests offline.
#
# Key type: ECDSA P-256 (nistP256) with SHA-256, using Windows CNG only, so the
# browser needs no third-party crypto library to verify a signature.
#
# Usage:  powershell -ExecutionPolicy Bypass -File scripts\generate_update_key.ps1
#         powershell ... -Force        # overwrite an existing private key

param([switch]$Force)
$ErrorActionPreference = 'Stop'

$repoRoot   = Split-Path -Parent $PSScriptRoot
$keyDir     = Join-Path $env:USERPROFILE '.mtk-signing'
$privatePath = Join-Path $keyDir 'update-private.blob'
$publicPath  = Join-Path $keyDir 'update-public.blob'
$headerPath  = Join-Path $repoRoot 'native\src\update_public_key.h'

if ((Test-Path $privatePath) -and -not $Force) {
    throw "A signing key already exists at $privatePath. Re-running would make every installed browser reject future updates. Pass -Force only if you are certain."
}

if (-not (Test-Path $keyDir)) { New-Item -ItemType Directory -Path $keyDir | Out-Null }

Add-Type -AssemblyName System.Core
$key = [System.Security.Cryptography.CngKey]::Create(
    [System.Security.Cryptography.CngAlgorithm]::ECDsaP256,
    $null,
    (New-Object System.Security.Cryptography.CngKeyCreationParameters -Property @{
        ExportPolicy = [System.Security.Cryptography.CngExportPolicies]::AllowPlaintextExport
    }))

# BCRYPT_ECCPRIVATE_BLOB / BCRYPT_ECCPUBLIC_BLOB: exactly what BCryptImportKeyPair
# consumes on the verifying side.
$privateBlob = $key.Export([System.Security.Cryptography.CngKeyBlobFormat]::EccPrivateBlob)
$publicBlob  = $key.Export([System.Security.Cryptography.CngKeyBlobFormat]::EccPublicBlob)
$key.Dispose()

[System.IO.File]::WriteAllBytes($privatePath, $privateBlob)
[System.IO.File]::WriteAllBytes($publicPath, $publicBlob)

# Restrict the private key to the current user.
$acl = Get-Acl $privatePath
$acl.SetAccessRuleProtection($true, $false)
$acl.Access | ForEach-Object { $acl.RemoveAccessRule($_) | Out-Null }
$acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule(
    "$env:USERDOMAIN\$env:USERNAME", 'FullControl', 'Allow')))
Set-Acl -Path $privatePath -AclObject $acl

$bytes = ($publicBlob | ForEach-Object { '0x{0:x2}' -f $_ })
$lines = @()
for ($index = 0; $index -lt $bytes.Count; $index += 12) {
    $slice = $bytes[$index..([Math]::Min($index + 11, $bytes.Count - 1))]
    $lines += '    ' + ($slice -join ', ') + ','
}

$header = @"
#pragma once

// Public key used to verify MTK Browser update manifests.
//
// Generated by scripts/generate_update_key.ps1. The matching private key lives
// outside this repository and is required to publish an update; it must never be
// committed. Replacing this key makes every already-installed browser reject
// future updates, so it is changed only as a deliberate key rotation.
//
// Format: BCRYPT_ECCPUBLIC_BLOB for ECDSA P-256, consumed directly by
// BCryptImportKeyPair.

#include <array>
#include <cstddef>

namespace mtk::update {

inline constexpr std::array<unsigned char, $($publicBlob.Length)> kUpdatePublicKey = {
$($lines -join "`n")
};

}  // namespace mtk::update
"@

Set-Content -Path $headerPath -Value $header -Encoding ASCII

Write-Output "Private key: $privatePath  ($($privateBlob.Length) bytes)"
Write-Output "Public key:  $publicPath   ($($publicBlob.Length) bytes)"
Write-Output "Header:      $headerPath"
Write-Output ''
Write-Output 'Back up the private key now. Without it you cannot publish updates,'
Write-Output 'and it must never be added to the repository.'
